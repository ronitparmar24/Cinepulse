#!/usr/bin/env python3
"""One-off generator: SQLite schema dump (JSON from sqlite_master) -> portable Postgres DDL.

Used to produce migrations/pg/0001_init.sql from the schema-13 SQLite database.
Kept in the repo so the translation rules are reviewable.

Rules
- INTEGER -> BIGINT (millisecond timestamps exceed int4); INTEGER PRIMARY KEY AUTOINCREMENT -> identity.
- REAL -> DOUBLE PRECISION; BOOLEAN -> SMALLINT (code stores 0/1 for both drivers).
- DATETIME / TIMESTAMP / DATE -> TEXT (SQLite stored ISO strings; values stay identical).
- datetime('now') / CURRENT_TIMESTAMP defaults -> UTC text in the same 'YYYY-MM-DD HH:MM:SS' shape.
- COLLATE NOCASE is dropped; case-insensitive uniqueness becomes a unique index on lower(col).
"""
import json
import re
import sys

src, out = sys.argv[1], sys.argv[2]
rows = json.load(open(src))
NOW_TEXT = "(to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))"

nocase_unique = []  # (table, column)


def table_ddl(name, sql):
    body = sql[sql.index('(') + 1: sql.rindex(')')]
    s = body
    s = re.sub(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", s, flags=re.I)
    s = re.sub(r"DEFAULT\s*\(\s*datetime\('now'\)\s*\)", "DEFAULT " + NOW_TEXT, s, flags=re.I)
    s = re.sub(r"DEFAULT\s*\(\s*CURRENT_TIMESTAMP\s*\)", "DEFAULT " + NOW_TEXT, s, flags=re.I)
    s = re.sub(r"DEFAULT\s+CURRENT_TIMESTAMP", "DEFAULT " + NOW_TEXT, s, flags=re.I)
    # Track NOT NULL UNIQUE COLLATE NOCASE columns
    for m in re.finditer(r"(\w+)\s+TEXT[^,]*?UNIQUE\s+COLLATE\s+NOCASE", s, flags=re.I):
        nocase_unique.append((name, m.group(1)))
    # Drop UNIQUE on NOCASE columns (replaced by lower() unique index) and the collation itself
    s = re.sub(r"\bUNIQUE\s+COLLATE\s+NOCASE", "", s, flags=re.I)
    s = re.sub(r"\s+COLLATE\s+NOCASE", "", s, flags=re.I)
    s = re.sub(r"\bINTEGER\b", "BIGINT", s, flags=re.I)
    s = re.sub(r"\bREAL\b", "DOUBLE PRECISION", s, flags=re.I)
    s = re.sub(r"\bBOOLEAN\b", "SMALLINT", s, flags=re.I)
    # SQLite stores these as text; keep the exact stored strings in Postgres.
    # Only the declared type (the word right after the column name), never a column named "date".
    s = re.sub(r"(^|,)(\s*\w+\s+)(DATETIME|TIMESTAMP|DATE)\b", r"\1\2TEXT", s, flags=re.I | re.M)
    # A column with no declared type defaults to TEXT
    lines = []
    for raw in s.split('\n'):
        lines.append(raw.rstrip())
    body = '\n'.join(lines).strip()
    return f"CREATE TABLE IF NOT EXISTS {name} (\n  {body}\n);"


def index_ddl(sql):
    s = re.sub(r"\s+COLLATE\s+NOCASE", "", sql, flags=re.I)
    # date(text) is not IMMUTABLE in Postgres; the ISO day prefix is equivalent for our values.
    s = re.sub(r"\bdate\((\w+)\)", r"substr(\1, 1, 10)", s, flags=re.I)
    s = re.sub(r"CREATE\s+(UNIQUE\s+)?INDEX\s+(?!IF NOT EXISTS)", lambda m: f"CREATE {m.group(1) or ''}INDEX IF NOT EXISTS ", s, flags=re.I)
    return s.rstrip(';') + ';'


tables = [r for r in rows if r['type'] == 'table' and r['name'] != 'sqlite_sequence']
indexes = [r for r in rows if r['type'] == 'index']

# Order tables so referenced tables come first
deps = {t['name']: set(re.findall(r"REFERENCES\s+(\w+)", t['sql'], flags=re.I)) - {t['name']} for t in tables}
ordered, seen = [], set()


def visit(n):
    if n in seen or n not in deps:
        return
    seen.add(n)
    for d in sorted(deps[n]):
        visit(d)
    ordered.append(n)


for t in sorted(deps):
    visit(t)
by_name = {t['name']: t for t in tables}

parts = ["-- CinePulse Postgres schema, generated from SQLite schema version 13",
         "-- by scripts/db/sqlite-schema-to-pg.py. Portable column types are used so the same",
         "-- SQL runs on both drivers (see lib/db/client.ts).", ""]
for n in ordered:
    parts.append(table_ddl(n, by_name[n]['sql']))
    parts.append('')
for i in indexes:
    parts.append(index_ddl(i['sql']))
parts.append('')
for t, c in nocase_unique:
    parts.append(f"CREATE UNIQUE INDEX IF NOT EXISTS {t}_{c}_lower_key ON {t} (lower({c}));")
open(out, 'w').write('\n'.join(parts) + '\n')
print(f"{len(ordered)} tables, {len(indexes)} indexes, nocase unique: {nocase_unique}")
